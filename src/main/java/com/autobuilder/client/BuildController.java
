    private void buildTick(MinecraftClient client, AutoBuilderConfig config) {
        ClientPlayerEntity player = client.player;
        boolean creative = isCreativeMode(client);

        int nextIndex = findNextPlaceable(client, config, creative);
        if (nextIndex == -2) {
            // Đang đập block đặt sai — chờ.
            tickCooldown = 1;
            return;
        }
        if (nextIndex < 0) {
            complete(client);
            return;
        }

        Schematic.Target target = schematic.targets().get(nextIndex);
        BlockPos worldPos = toWorld(target, config);
        currentTarget = worldPos;

        // Tuyến phòng thủ thứ hai: không bao giờ đặt chất lỏng.
        if (BlockStateParser.isLiquidState(target.state())) {
            done.set(nextIndex);
            liquidSkipped++;
            status = "Bỏ qua chất lỏng · còn " + remaining() + " block";
            return;
        }

        BlockState desired = BlockStateParser.parse(target.state());
        if (config.autoCamera) {
            lookAt(player, Vec3d.ofCenter(worldPos));
        }

        double distance = player.getEyePos().distanceTo(Vec3d.ofCenter(worldPos));
        if (distance > MAX_REACH) {
            if (config.autoApproach) {
                expectMovement = true;
                boolean moved = stepToward(client, worldPos, STOP_DISTANCE);
                status = moved
                        ? "Đang tới gần · còn " + remaining() + " block"
                        : "Đang tìm đường tới gần";
                tickCooldown = 1;
            } else {
                expectMovement = false;
                status = "Ngoài tầm với — bật 'Tới gần' hoặc tự bước lại";
                warnThrottled(client, status);
                tickCooldown = 10;
            }
            return;
        }
        expectMovement = false;

        // Xây trên cao: tự bắc giàn giáo.
        if (config.autoScaffold && worldPos.getY() > player.getY() + 3.0) {
            if (scaffoldUp(client)) {
                tickCooldown = 2;
            } else {
                status = "Cần item scaffolding trong hotbar để xây cao";
                warnThrottled(client, status);
                tickCooldown = 20;
            }
            return;
        }

        if (!ensureItem(client, desired, creative)) {
            if (!creative && config.resupplyFromChest && config.useChest) {
                startResupply(client, desired.getBlock().asItem());
            } else if (!creative && config.resupplyFromChest && !config.useChest) {
                status = "Thiếu block · " + desired.getBlock().getName().getString() + " · chưa bật toạ độ rương";
                if (noMaterialNoticeTicks <= 0) {
                    AutoBuilderClient.webhook("📦 AutoBuilder hết '"
                            + desired.getBlock().getName().getString() + "' và chưa cấu hình rương đồ.");
                    noMaterialNoticeTicks = 600;
                }
                warnThrottled(client, status);
                tickCooldown = 20;
            } else {
                status = creative
                        ? "Creative: không lấy được item này"
                        : "Thiếu block · " + desired.getBlock().getName().getString();
                warnThrottled(client, status);
                tickCooldown = 20;
            }
            // KHÔNG tắt mod: tạm dừng, chờ người chơi bổ sung vật liệu.
            return;
        }

        if (placeAt(client, worldPos)) {
            done.set(nextIndex);
            placed++;
            tickCooldown = config.placeDelayTicks;
            status = placed + " đã đặt · còn " + remaining() + " block";
            if (done.cardinality() >= schematic.blocks()) {
                complete(client);
            }
        } else {
            status = "Chưa đặt được · đang tìm mặt đỡ khác";
            tickCooldown = 8;
        }
    }

    /**
     * Tìm block tiếp theo. Trả về:
     * - index >= 0: block cần đặt;
     * - -1: hết việc (hoàn thành);
     * - -2: đang bận đập block đặt sai.
     */
    private int findNextPlaceable(MinecraftClient client, AutoBuilderConfig config, boolean creative) {
        World world = client.world;
        if (world == null) {
            return -1;
        }

        while (true) {
            if (breakingPos != null) {
                int breaking = continueBreaking(client, creative);
                if (breaking != 0) {
                    return breaking;
                }
                // Đập xong — vòng lặp chọn block kế tiếp.
            }

            int candidate = done.nextClearBit(0);
            if (candidate >= schematic.blocks()) {
                return -1;
            }

            Schematic.Target target = schematic.targets().get(candidate);
            BlockPos pos = toWorld(target, config);

            // Chất lỏng được xử lý ở buildTick (đánh dấu bỏ qua).
            if (BlockStateParser.isLiquidState(target.state())) {
                return candidate;
            }

            BlockState current = world.getBlockState(pos);
            BlockState desired = BlockStateParser.parse(target.state());

            if (current.getBlock() == desired.getBlock()) {
                done.set(candidate);
                continue;
            }
            if (current.isReplaceable()) {
                return candidate;
            }

            // Ô mục tiêu đang bị chiếm bởi block KHÁC loại — block đặt sai.
            if (!config.breakWrongBlocks) {
                done.set(candidate);
                skipped++;
                continue;
            }
            if (creative) {
                if (client.interactionManager != null) {
                    client.interactionManager.attackBlock(pos, Direction.UP);
                    breakingPos = pos;
                    breakingIndex = candidate;
                    breakingTicks = 0;
                    status = "Đập block đặt sai tại " + pos.toShortString();
                } else {
                    done.set(candidate);
                    skipped++;
                }
                return -2;
            }
            breakingPos = pos;
            breakingIndex = candidate;
            breakingTicks = 0;
            status = "Đang đào block đặt sai tại " + pos.toShortString();
            return -2;
        }
    }

    /**
     * Tiếp tục đào block sai. Trả về 0 khi xong, -2 khi còn bận.
     * Quá 100 tick (5 giây) thì huỷ và bỏ qua block đó.
     */
    private int continueBreaking(MinecraftClient client, boolean creative) {
        World world = client.world;
        if (world == null || client.interactionManager == null || breakingPos == null) {
            breakingPos = null;
            breakingIndex = -1;
            return 0;
        }

        BlockState state = world.getBlockState(breakingPos);
        if (state.isAir() || state.isReplaceable()) {
            client.interactionManager.cancelBlockBreaking();
            breakingPos = null;
            breakingIndex = -1;
            status = "Đã đập xong block đặt sai";
            return 0;
        }

        breakingTicks++;
        if (breakingTicks > 100) {
            client.interactionManager.cancelBlockBreaking();
            if (breakingIndex >= 0) {
                done.set(breakingIndex);
                skipped++;
            }
            breakingPos = null;
            breakingIndex = -1;
            status = "Không đào được — bỏ qua block này";
            return 0;
        }

        if (!creative) {
            client.interactionManager.updateBlockBreakingProgress(breakingPos, Direction.UP);
        } else if (breakingTicks % 5 == 0) {
            client.interactionManager.attackBlock(breakingPos, Direction.UP);
        }
        return -2;
    }

    private BlockPos toWorld(Schematic.Target target, AutoBuilderConfig config) {
        return new BlockPos(
                config.originX + target.x(),
                config.originY + target.y(),
                config.originZ + target.z()
        );
    }

