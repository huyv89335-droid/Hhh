    public double progress() {
        int total = schematic == null ? 0 : schematic.blocks();
        if (total == 0 || done == null) {
            return 0.0;
        }
        return Math.min(1.0, (double) done.cardinality() / total);
    }

    public int remaining() {
        int total = schematic == null ? 0 : schematic.blocks();
        return Math.max(0, total - done.cardinality());
    }

    public boolean toggle(MinecraftClient client) {
        if (enabled) {
            stop(client, "Đã tắt thủ công");
            return false;
        }
        return start(client);
    }

    public boolean start(MinecraftClient client) {
        if (client.player == null || client.world == null) {
            status = "Chưa vào thế giới";
            return false;
        }
        if (schematic == null || schematic.blocks() == 0) {
            status = "Chưa chọn bản vẽ hợp lệ";
            announce(client, status);
            return false;
        }

        AutoBuilderConfig config = AutoBuilderClient.config();
        config.sanitize();
        done = new BitSet(schematic.blocks());
        placed = 0;
        skipped = 0;
        liquidSkipped = 0;
        tickCooldown = 0;
        warningCooldown = 0;
        overlayCooldown = 0;
        currentTarget = null;
        breakingPos = null;
        breakingIndex = -1;
        resupplyPhase = RESUPPLY_NONE;
        resumePos = null;
        resupplyItem = null;
        stuckTicks = 0;
        detourTicks = 0;
        stuckWebhookSent = false;
        eating = false;
        enabled = true;
        status = "Đang xây · " + schematic.fileName();
        announce(client, "AutoBuilder bật · " + schematic.blocks() + " block · chế độ " + modeLabel(client));
        AutoBuilderClient.webhook("🏗️ AutoBuilder bắt đầu '" + schematic.fileName() + "' ("
                + schematic.blocks() + " block) tại " + config.originX + " " + config.originY + " " + config.originZ);
        AutoBuilder.LOGGER.info("Build started: {} (mode {})", schematic.fileName(), config.mode);
        return true;
    }

    public void stop(MinecraftClient client, String reason) {
        if (enabled) {
            AutoBuilder.LOGGER.info("Build stopped: {} ({})", schematic == null ? "-" : schematic.fileName(), reason);
        }
        enabled = false;
        stopEating(client);
        resupplyPhase = RESUPPLY_NONE;
        resumePos = null;
        resupplyItem = null;
        breakingPos = null;
        breakingIndex = -1;
        expectMovement = false;
        status = reason;
    }

    /**
     * Được gọi ở END_CLIENT_TICK.
     */
    public void tick(MinecraftClient client) {
        if (!enabled) {
            return;
        }
        if (client.player == null || client.world == null) {
            stop(client, "Thế giới chưa sẵn sàng");
            return;
        }
        // Màn hình đang mở: tạm dừng. Ngoại lệ duy nhất là màn hình rương
        // do chính luồng resupply mở ra.
        if (client.currentScreen != null && resupplyPhase != RESUPPLY_OPEN_CHEST) {
            return;
        }
        if (warningCooldown > 0) {
            warningCooldown--;
        }
        if (overlayCooldown > 0) {
            overlayCooldown--;
        }
        if (scaffoldCooldown > 0) {
            scaffoldCooldown--;
        }
        if (noMaterialNoticeTicks > 0) {
            noMaterialNoticeTicks--;
        }

        updateOverlay(client);
        updateStuckDetection(client);

        // Tự ăn được ưu tiên cao nhất.
        if (handleEating(client)) {
            tickCooldown = 2;
            return;
        }

        if (tickCooldown > 0) {
            tickCooldown--;
            if (currentTarget != null
                    && AutoBuilderClient.config().autoCamera
                    && resupplyPhase == RESUPPLY_NONE) {
                lookAt(client.player, Vec3d.ofCenter(currentTarget));
            }
            return;
        }

        AutoBuilderConfig config = AutoBuilderClient.config();

        switch (resupplyPhase) {
            case RESUPPLY_WALK_TO_CHEST -> {
                walkToChest(client, config);
                return;
            }
            case RESUPPLY_OPEN_CHEST -> {
                handleChestScreen(client, config);
                return;
            }
            case RESUPPLY_RETURN -> {
                walkBack(client);
                return;
            }
            default -> {
            }
        }

        buildTick(client, config);
    }

