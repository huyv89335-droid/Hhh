    public void setSchematic(Schematic schematic) {
        this.schematic = schematic;
        this.done = new BitSet(schematic == null ? 0 : schematic.blocks());
        this.enabled = false;
        this.placed = 0;
        this.skipped = 0;
        this.liquidSkipped = 0;
        this.currentTarget = null;
        this.tickCooldown = 0;
        this.breakingPos = null;
        this.breakingIndex = -1;
        this.resupplyPhase = RESUPPLY_NONE;
        this.resumePos = null;
        this.resupplyItem = null;
        this.stuckTicks = 0;
        this.detourTicks = 0;
        this.status = schematic == null
                ? "Chưa chọn bản vẽ"
                : "Sẵn sàng · " + schematic.blocks() + " block";
    }

