/**
 * Bộ điều khiển xây — BƯỚC 2 (treo máy AFK).
 *
 * Tính năng bước 2:
 * 1. Chế độ CREATIVE / SURVIVAL / AUTO:
 *    - Creative: tự lấy block từ kho sáng tạo (clickCreativeStack).
 *    - Survival: hết block -> lưu vị trí, chạy về rương đã cấu hình,
 *      QUICK_MOVE đúng loại block thiếu, quay lại xây tiếp.
 * 2. Anti-stuck: kẹt 3 giây -> nhảy; 6 giây -> đi vòng vuông góc;
 *    15 giây -> webhook + bỏ qua chặng di chuyển đó (mod VẪN BẬT).
 *    Block đặt sai vị trí/sai loại bị đập bỏ (creative đập ngay,
 *    survival đào từ từ tối đa 5 giây rồi bỏ qua).
 * 3. Xây tầng cao: tự bắc scaffolding khi mục tiêu cao hơn 3 block.
 *    Thứ tự xây đã được Schematic.sortByBuildOrder sắp "dưới lên trên,
 *    trong ra ngoài". Chất lỏng (nước/lava/bubble column) TUYỆT ĐỐI
 *    không đặt — đánh dấu xong và đếm riêng.
 * 4. Tự ăn khi đói (data component FOOD), hiển thị số block còn lại
 *    trên action bar mỗi giây, tự tắt khi đạt 100%.
 *
 * "Không tự động tắt khi đang xây": lỗi tạm thời (thiếu đồ, ngoài tầm với,
 * kẹt địa hình, màn hình đang mở) chỉ TẠM DỪNG rồi thử lại. Mod chỉ tắt khi:
 * (a) hoàn thành 100%, (b) người chơi tắt thủ công, (c) rời thế giới.
 *
 * Nguyên tắc an toàn giữ nguyên từ bước 1: không cheat packet, không phá
 * block ngoài schematic (trừ block đặt sai tại ô mục tiêu), mọi thao tác
 * qua interactionManager như người chơi thật.
 */
