package com.autobuilder.client;

import com.autobuilder.AutoBuilder;
import com.google.gson.JsonObject;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

/**
 * Gửi Discord webhook ở chế độ nền — không bao giờ chặn client tick.
 *
 * Chỉ nhận URL https:// (Discord webhook). URL được kiểm tra trong
 * AutoBuilderConfig.sanitize(); ở đây chỉ gửi và ghi log lỗi.
 */
public final class WebhookNotifier {
    private static final HttpClient HTTP = HttpClient.newBuilder()
            .connectTimeout(Duration.ofSeconds(6))
            .build();

    private static final ExecutorService POOL = Executors.newSingleThreadExecutor(runnable -> {
        Thread thread = new Thread(runnable, "AutoBuilder-Webhook");
        thread.setDaemon(true);
        return thread;
    });

    private WebhookNotifier() {
    }

    /**
     * Gửi một tin nhắn text đơn giản. Bỏ qua im lặng nếu URL trống.
     */
    public static void send(String webhookUrl, String content) {
        if (webhookUrl == null || webhookUrl.isBlank()) {
            return;
        }
        if (!webhookUrl.startsWith("https://")) {
            AutoBuilder.LOGGER.warn("Webhook bị bỏ qua: URL phải là https://");
            return;
        }

        final String url = webhookUrl.trim();
        POOL.submit(() -> {
            try {
                JsonObject body = new JsonObject();
                body.addProperty("content", content);
                body.addProperty("username", "AutoBuilder");

                HttpRequest request = HttpRequest.newBuilder()
                        .uri(URI.create(url))
                        .timeout(Duration.ofSeconds(8))
                        .header("Content-Type", "application/json; charset=utf-8")
                        .POST(HttpRequest.BodyPublishers.ofString(body.toString(), StandardCharsets.UTF_8))
                        .build();

                HttpResponse<String> response = HTTP.send(request, HttpResponse.BodyHandlers.ofString());
                if (response.statusCode() >= 200 && response.statusCode() < 300) {
                    AutoBuilder.LOGGER.info("Webhook sent (HTTP {}).", response.statusCode());
                } else {
                    AutoBuilder.LOGGER.warn("Webhook HTTP {}: {}", response.statusCode(), response.body());
                }
            } catch (Exception exception) {
                AutoBuilder.LOGGER.warn("Webhook failed: {}", exception.getMessage());
            }
        });
    }
}