package com.autobuilder.schematic;

import net.minecraft.block.Block;
import net.minecraft.block.BlockState;
import net.minecraft.block.Blocks;
import net.minecraft.registry.Registries;
import net.minecraft.state.property.Property;
import net.minecraft.util.Identifier;

import java.util.HashMap;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;

/**
 * Parser nhỏ, không phụ thuộc Brigadier.
 *
 * Ví dụ đầu vào:
 * minecraft:oak_stairs[facing=north,half=bottom,shape=straight,waterlogged=false]
 *
 * Nếu một property không tồn tại hoặc giá trị không hợp lệ, property đó bị bỏ
 * qua và block vẫn được đặt với state mặc định. Cách này ưu tiên "không crash"
 * hơn là dừng cả công trình vì một khác biệt palette nhỏ.
 */
public final class BlockStateParser {
    private BlockStateParser() {
    }

    public static BlockState parse(String rawState) {
        if (rawState == null || rawState.isBlank()) {
            return Blocks.AIR.getDefaultState();
        }

        String raw = rawState.trim();
        String namePart = raw;
        String propsPart = "";

        int bracket = raw.indexOf('[');
        if (bracket >= 0) {
            int end = raw.lastIndexOf(']');
            namePart = raw.substring(0, bracket).trim();
            if (end > bracket) {
                propsPart = raw.substring(bracket + 1, end);
            }
        }

        if (!namePart.contains(":")) {
            namePart = "minecraft:" + namePart;
        }

        Identifier identifier = Identifier.tryParse(namePart.toLowerCase(Locale.ROOT));
        if (identifier == null) {
            return Blocks.AIR.getDefaultState();
        }

        Block block = Registries.BLOCK.get(identifier);
        if (block == null) {
            return Blocks.AIR.getDefaultState();
        }

        BlockState state = block.getDefaultState();
        if (propsPart.isBlank()) {
            return state;
        }

        Map<String, Property<?>> available = new HashMap<>();
        for (Property<?> property : state.getProperties()) {
            available.put(property.getName(), property);
        }

        for (String token : propsPart.split(",")) {
            String pair = token.trim();
            if (pair.isEmpty()) {
                continue;
            }
            int equals = pair.indexOf('=');
            if (equals <= 0 || equals >= pair.length() - 1) {
                continue;
            }
            String propertyName = pair.substring(0, equals).trim();
            String propertyValue = pair.substring(equals + 1).trim().toLowerCase(Locale.ROOT);
            Property<?> property = available.get(propertyName);
            if (property != null) {
                state = applyProperty(state, property, propertyValue);
            }
        }

        return state;
    }

    @SuppressWarnings({"rawtypes", "unchecked"})
    private static BlockState applyProperty(BlockState state, Property property, String value) {
        Optional parsed = property.parse(value);
        if (parsed.isEmpty()) {
            return state;
        }
        return (BlockState) state.with(property, (Comparable) parsed.get());
    }

    public static boolean isAirState(String rawState) {
        if (rawState == null) {
            return true;
        }
        String state = rawState.trim().toLowerCase(Locale.ROOT);
        int bracket = state.indexOf('[');
        if (bracket >= 0) {
            state = state.substring(0, bracket);
        }
        return state.equals("air")
                || state.equals("minecraft:air")
                || state.equals("cave_air")
                || state.equals("minecraft:cave_air")
                || state.equals("void_air")
                || state.equals("minecraft:void_air")
                || state.equals("structure_void")
                || state.equals("minecraft:structure_void");
    }

    /**
     * Bước 2 — chất lỏng không bao giờ được đặt tự động.
     * Bao gồm cả dạng chảy (cùng id, khác level) và cột bọt khí.
     */
    public static boolean isLiquidState(String rawState) {
        if (rawState == null) {
            return false;
        }
        String state = rawState.trim().toLowerCase(Locale.ROOT);
        int bracket = state.indexOf('[');
        if (bracket >= 0) {
            state = state.substring(0, bracket);
        }
        return state.equals("water")
                || state.equals("minecraft:water")
                || state.equals("flowing_water")
                || state.equals("minecraft:flowing_water")
                || state.equals("lava")
                || state.equals("minecraft:lava")
                || state.equals("flowing_lava")
                || state.equals("minecraft:flowing_lava")
                || state.equals("bubble_column")
                || state.equals("minecraft:bubble_column");
    }
}